const columns = (privilege: string, table: string, names: readonly string[]) =>
  names.map((name) => `${privilege} on column privacy.${table}.${name}`);

export const privacy: SchemaCatalogue = {
  // The erasure job, once the party is erased (ADR 0027).
  executableBy: [['privacy.erase_subject(uuid)', ['app_worker']]],
  definerFunctions: [
    [
      'privacy.erase_subject(uuid)',
      {
        owner: 'owner_privacy_erase_subject',
        // Never DELETE, nor any column that says who or when.
        rights: [
          'USAGE on schema app',
          'USAGE on schema party',
          'USAGE on schema privacy',
          'EXECUTE on function app.current_tenant_id()',
          ...['tenant_id', 'id', 'status'].map((name) => `SELECT on column party.party.${name}`),
          ...columns('SELECT', 'rights_request', [
            'tenant_id',
            'id',
            'subject_person_id',
            'summary',
          ]),
          ...columns('UPDATE', 'rights_request', ['summary']),
          ...columns('SELECT', 'request_task', ['tenant_id', 'request_id', 'title']),
          ...columns('UPDATE', 'request_task', ['title']),
        ],
        policies: [],
      },
    ],
  ],
};

